--  (1회용) 현재 모든 유저의 프로필 사진을 기본 프로필 사진으로 되돌림
--  사용법: Supabase 대시보드 → SQL Editor → New query → 붙여넣기 → Run
--  * 실행할 때마다 그 시점의 모든 유저 사진이 지워지므로 딱 한 번만 실행하세요.
--  * 이미 올라간 사진 파일(avatars 버킷)은 그대로 남습니다. (화면에는 더 이상 쓰이지 않음)
--  * 사이트 화면에는 최대 1분 뒤에 반영됩니다. (프로필 사진 캐시)
-- =====================================================================

update public.profiles
   set avatar_url = null
 where avatar_url is not null;

-- 확인용: 0 이 나오면 모든 유저가 기본 프로필 사진입니다.
select count(*) as "사진이 남아 있는 유저 수" from public.profiles where avatar_url is not null;
